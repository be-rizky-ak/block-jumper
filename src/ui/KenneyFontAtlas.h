    inline const GlyphMetric* GetKenneyGlyph(char c)
    {
        unsigned char uc = static_cast<unsigned char>(c);
        if (uc >= 32 && uc <= 126)
        {
            return &s_KenneyGlyphs[uc - 32];
        }
        return &s_KenneyGlyphs[0]; // space fallback
    }
